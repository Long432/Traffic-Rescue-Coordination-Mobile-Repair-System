/* ---------- 1. NguoiDung ---------- */
CREATE TABLE NguoiDung (
    Id                 SERIAL PRIMARY KEY,
    HoTen              VARCHAR(100) NOT NULL,
    SoDienThoai        VARCHAR(15)   NOT NULL UNIQUE,
    MatKhauHash        VARCHAR(100)  NOT NULL,
    VaiTro             VARCHAR(10)   NOT NULL CHECK (VaiTro IN ('USER','THO','ADMIN')),
    TrangThaiTaiKhoan  VARCHAR(10)   NOT NULL DEFAULT 'HOAT_DONG'
                        CHECK (TrangThaiTaiKhoan IN ('HOAT_DONG','BI_KHOA')),
    KhoaDen            TIMESTAMP     NULL,
    NgayTao            TIMESTAMP     NOT NULL DEFAULT NOW()
);

/* ---------- 2. LoaiSuCo ---------- */
CREATE TABLE LoaiSuCo (
    Id          SERIAL PRIMARY KEY,
    TenSuCo     VARCHAR(100) NOT NULL,
    GiaCoBan    DECIMAL(12,0) NOT NULL,
    MucKhanCap  SMALLINT      NOT NULL CHECK (MucKhanCap BETWEEN 1 AND 3)
);

/* ---------- 3. Tho ---------- */
CREATE TABLE Tho (
    Id               INT NOT NULL PRIMARY KEY
                      REFERENCES NguoiDung(Id),
    TrangThaiOnline  BOOLEAN       NOT NULL CONSTRAINT DF_Tho_Online DEFAULT FALSE,
    IsBusy           BOOLEAN       NOT NULL CONSTRAINT DF_Tho_Busy DEFAULT FALSE,
    DiemUyTin        INT           NOT NULL CONSTRAINT DF_Tho_Uytin DEFAULT 100,
    DiemTrungBinh    DECIMAL(3,2)  NOT NULL CONSTRAINT DF_Tho_Diem DEFAULT 5.00,
    TiLeNhanCuoc     DECIMAL(4,3)  NOT NULL CONSTRAINT DF_Tho_TiLe DEFAULT 1.000,
    DaDuyet          BOOLEAN       NOT NULL CONSTRAINT DF_Tho_Duyet DEFAULT FALSE
);

/* Tho lam duoc nhung loai su co nao (nhieu-nhieu) */
CREATE TABLE ThoLoaiSuCo (
    ThoId       INT NOT NULL REFERENCES Tho(Id),
    LoaiSuCoId  INT NOT NULL REFERENCES LoaiSuCo(Id),
    CONSTRAINT PK_ThoLoaiSuCo PRIMARY KEY (ThoId, LoaiSuCoId)
);

/* ---------- 4. ViTriTho (vi tri moi nhat, 1 dong moi tho) ---------- */
CREATE TABLE ViTriTho (
    ThoId       INT NOT NULL PRIMARY KEY
                REFERENCES Tho(Id),
    Latitude    DECIMAL(9,6) NOT NULL,
    Longitude   DECIMAL(9,6) NOT NULL,
    CapNhatLuc  TIMESTAMP    NOT NULL DEFAULT NOW()
);
CREATE INDEX IX_ViTriTho_ToaDo ON ViTriTho (Latitude, Longitude);

/* ---------- 5. CuocCuuHo ---------- */
CREATE TABLE CuocCuuHo (
    Id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    KhachId      INT NOT NULL REFERENCES NguoiDung(Id),
    ThoId        INT NULL     REFERENCES Tho(Id),
    LoaiSuCoId   INT NOT NULL REFERENCES LoaiSuCo(Id),
    Latitude     DECIMAL(9,6) NOT NULL,
    Longitude    DECIMAL(9,6) NOT NULL,
    DiaChi       VARCHAR(255) NULL,
    GhiChu       VARCHAR(500) NULL,
    TrangThai    VARCHAR(20)  NOT NULL DEFAULT 'DANG_TIM'
                  CHECK (TrangThai IN
                    ('DANG_TIM','DA_NHAN','DANG_DEN','DA_DEN','DANG_SUA','CHO_THANH_TOAN','HOAN_THANH','HUY','KHONG_CO_THO')),
    GiaUocTinh   DECIMAL(12,0) NOT NULL,
    TongTien     DECIMAL(12,0) NULL,
    LyDoHuy      VARCHAR(255) NULL,
    NgayTao      TIMESTAMP    NOT NULL DEFAULT NOW(),
    /* Moc bat dau dem thoi gian tim tho; dat lai khi tho tra cuoc (xem QuyTacPhatCuoc) */
    BatDauTimLuc TIMESTAMP    NOT NULL DEFAULT NOW(),
    RowVersion   TIMESTAMP
);
CREATE INDEX IX_Cuoc_TrangThai ON CuocCuuHo (TrangThai);
CREATE INDEX IX_Cuoc_Tho ON CuocCuuHo (ThoId, TrangThai);
CREATE INDEX IX_Cuoc_Khach ON CuocCuuHo (KhachId, NgayTao DESC);

/* ---------- 6. LichSuTrangThai ---------- */
CREATE TABLE LichSuTrangThai (
    Id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CuocId           BIGINT NOT NULL REFERENCES CuocCuuHo(Id),
    TuTrangThai      VARCHAR(20) NULL,
    DenTrangThai     VARCHAR(20) NOT NULL,
    ThoiGian         TIMESTAMP   NOT NULL DEFAULT NOW(),
    NguoiThucHienId  INT NULL REFERENCES NguoiDung(Id),
    GhiChu           VARCHAR(255) NULL
);
CREATE INDEX IX_LichSu_Cuoc ON LichSuTrangThai (CuocId, ThoiGian);

/* ---------- 7. VatTuPhatSinh ---------- */
CREATE TABLE VatTuPhatSinh (
    Id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CuocId          BIGINT NOT NULL REFERENCES CuocCuuHo(Id),
    TenVatTu        VARCHAR(100) NOT NULL,
    DonGia          DECIMAL(12,0) NOT NULL,
    SoLuong         INT NOT NULL CONSTRAINT DF_VatTu_SL DEFAULT 1 CONSTRAINT CK_VatTu_SL CHECK (SoLuong > 0),
    KhachDaXacNhan  BOOLEAN NOT NULL CONSTRAINT DF_VatTu_XN DEFAULT FALSE
);

/* ---------- 8. DanhGia ---------- */
CREATE TABLE DanhGia (
    Id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CuocId   BIGINT NOT NULL UNIQUE
             REFERENCES CuocCuuHo(Id),
    SoSao    SMALLINT NOT NULL CONSTRAINT CK_DanhGia_Sao CHECK (SoSao BETWEEN 1 AND 5),
    NhanXet  VARCHAR(500) NULL,
    NgayTao  TIMESTAMP NOT NULL DEFAULT NOW()
);

